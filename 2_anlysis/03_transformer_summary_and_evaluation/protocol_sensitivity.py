"""
Protocol-stratified sensitivity analysis for Fig. 4 coordination result.

Purpose
-------
Tests whether the direction of the leaf coordination advantage is retained
within each osmotic-stress protocol.

Primary question
----------------
Within each protocol, at peak stress / Time Point 3:
    G1 coordination > G2 coordination ?

This script does not regenerate attention tensors or retrain the model.
It uses the plant-level Fig. 4 source table generated by Figure_4_c_f.py.

Expected input
--------------
fig4_plant_data.csv with at least:
    Tissue
    Genotype
    Time_Point
    Coordination_Score
    Treatment
plus one protocol-identifying column, e.g.:
    Protocol / Stress_Protocol / Sorbitol / Stress_Level / Batch / Experiment
"""

import os
import numpy as np
import pandas as pd
from scipy.stats import mannwhitneyu


BASE_DIR = r"C:\Users\ms\Desktop\hyper"

INPUT_FILE = os.path.join(
    BASE_DIR,
    "output",
    "transformer",
    "novility_plot",
    "final",
    "fig4_plant_data.csv"
)

OUTPUT_DIR = os.path.join(
    BASE_DIR,
    "output",
    "transformer",
    "novility_plot",
    "final"
)

OUTPUT_FILE = os.path.join(
    OUTPUT_DIR,
    "fig4_protocol_stratified_sensitivity.csv"
)

PEAK_TIME_POINT = 3
PRIMARY_TISSUE = "Leaf"
COORDINATION_COL = "Coordination_Score"


def find_protocol_column(df: pd.DataFrame) -> str:
    """Find protocol-identifying column without guessing silently."""
    candidates = [
        "Protocol",
        "Stress_Protocol",
        "StressProtocol",
        "Sorbitol",
        "Sorbitol_M",
        "Stress_Level",
        "StressLevel",
        "Experiment",
        "Batch"
    ]

    found = [c for c in candidates if c in df.columns]

    if not found:
        raise ValueError(
            "No protocol-identifying column found. Add or map one column before running. "
            "Expected one of: " + ", ".join(candidates)
        )

    if len(found) > 1:
        print(f"Multiple possible protocol columns found: {found}")
        print(f"Using first candidate: {found[0]}")

    return found[0]


def standardise_labels(df: pd.DataFrame, protocol_col: str) -> pd.DataFrame:
    """Standardise key labels used in the sensitivity analysis."""
    df = df.copy()

    df["Tissue"] = df["Tissue"].astype(str).str.strip()
    df["Genotype"] = df["Genotype"].astype(str).replace({
        "1": "G1",
        "1.0": "G1",
        "Gladius": "G1",
        "2": "G2",
        "2.0": "G2",
        "DAS5_003811": "G2"
    })

    df["Time_Point"] = df["Time_Point"].astype(int)

    if "Treatment" in df.columns:
        df["Treatment"] = df["Treatment"].astype(str).replace({
            "1": "T1",
            "1.0": "T1",
            "0": "T0",
            "0.0": "T0"
        })

    df[protocol_col] = df[protocol_col].astype(str).str.strip()

    return df


def summarise_protocol_contrast(df: pd.DataFrame, protocol_col: str) -> pd.DataFrame:
    """Compare G1 and G2 coordination within each protocol."""
    required_cols = {
        "Tissue",
        "Genotype",
        "Time_Point",
        COORDINATION_COL,
        protocol_col
    }

    missing = required_cols - set(df.columns)
    if missing:
        raise ValueError(f"Missing required columns: {missing}")

    # Primary sensitivity: stressed plants, leaf, peak phase
    work = df.copy()

    if "Treatment" in work.columns:
        work = work[work["Treatment"] == "T1"]

    work = work[
        (work["Tissue"] == PRIMARY_TISSUE) &
        (work["Time_Point"] == PEAK_TIME_POINT)
    ].copy()

    if work.empty:
        raise ValueError(
            "No rows found for primary sensitivity subset: "
            f"Tissue={PRIMARY_TISSUE}, Time_Point={PEAK_TIME_POINT}, Treatment=T1 if available."
        )

    rows = []

    for protocol, sub in work.groupby(protocol_col):
        g1 = sub[sub["Genotype"] == "G1"][COORDINATION_COL].dropna().astype(float)
        g2 = sub[sub["Genotype"] == "G2"][COORDINATION_COL].dropna().astype(float)

        if len(g1) < 2 or len(g2) < 2:
            rows.append({
                "Protocol": protocol,
                "Tissue": PRIMARY_TISSUE,
                "Time_Point": PEAK_TIME_POINT,
                "n_G1": len(g1),
                "n_G2": len(g2),
                "G1_median": np.nan,
                "G2_median": np.nan,
                "G1_minus_G2": np.nan,
                "Fold_change_G1_over_G2": np.nan,
                "Direction_retained": False,
                "p_value": np.nan,
                "Status": "insufficient_samples"
            })
            continue

        g1_median = float(np.median(g1))
        g2_median = float(np.median(g2))
        diff = g1_median - g2_median

        if g2_median > 0:
            fold_change = g1_median / g2_median
        else:
            fold_change = np.nan

        _, p_value = mannwhitneyu(g1, g2, alternative="two-sided")

        rows.append({
            "Protocol": protocol,
            "Tissue": PRIMARY_TISSUE,
            "Time_Point": PEAK_TIME_POINT,
            "n_G1": len(g1),
            "n_G2": len(g2),
            "G1_median": g1_median,
            "G2_median": g2_median,
            "G1_minus_G2": diff,
            "Fold_change_G1_over_G2": fold_change,
            "Direction_retained": bool(diff > 0),
            "p_value": float(p_value),
            "Status": "computed"
        })

    result = pd.DataFrame(rows)

    if result.empty:
        raise RuntimeError("No protocol-stratified contrasts were computed.")

    computed = result[result["Status"] == "computed"]

    if computed.empty:
        raise RuntimeError(
            "All protocol-stratified contrasts failed due to insufficient samples."
        )

    return result


def main():
    if not os.path.exists(INPUT_FILE):
        raise FileNotFoundError(
            f"Input file not found: {INPUT_FILE}\n"
            "Run Figure_4_c_f.py first, or update INPUT_FILE to the actual fig4_plant_data.csv path."
        )

    os.makedirs(OUTPUT_DIR, exist_ok=True)

    df = pd.read_csv(INPUT_FILE)
    print(f"Loaded: {INPUT_FILE}")
    print(f"Rows: {len(df)}")
    print(f"Columns: {list(df.columns)}")

    protocol_col = find_protocol_column(df)
    print(f"Using protocol column: {protocol_col}")

    df = standardise_labels(df, protocol_col)
    result = summarise_protocol_contrast(df, protocol_col)

    result.to_csv(OUTPUT_FILE, index=False)
    print(f"\nSaved protocol-stratified sensitivity table:\n{OUTPUT_FILE}")

    print("\nSummary:")
    print(result.to_string(index=False))

    computed = result[result["Status"] == "computed"]
    all_retained = computed["Direction_retained"].all()

    if all_retained:
        print(
            "\nConclusion: Direction retained. "
            "G1 coordination exceeds G2 coordination within all computable protocols."
        )
    else:
        print(
            "\nConclusion: Direction not retained across all computable protocols. "
            "Do not use the stronger manuscript sentence."
        )


if __name__ == "__main__":
    main()